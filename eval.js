const PST = [null, PST_PAWN, PST_KNIGHT, PST_BISHOP, PST_ROOK, PST_QUEEN, PST_KING];
const MIRROR = new Int8Array(64);
for (let sq = 0; sq < 64; sq++) MIRROR[sq] = ((7 - (sq >> 3)) << 3) | (sq & 7);

// повертає оцінку з погляду сторони, що має хід
export function evaluate(p, trophyValue = TROPHY_VALUE) {
  let s = 0;
  for (let sq = 0; sq < 64; sq++) {
    const pc = p.board[sq];
    if (!pc) continue;
    const t = typeOf(pc), c = colorOf(pc);
    let v = MATERIAL[t] + PST[t][c === WHITE ? sq : MIRROR[sq]];
    if (p.rules.trophies) {
      if (p.t1[sq]) v += trophyValue[p.t1[sq]];
      if (p.t2[sq]) v += trophyValue[p.t2[sq]];
    }
    s += c === WHITE ? v : -v;
  }
  return p.side === WHITE ? s : -s;
}
